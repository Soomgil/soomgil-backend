package com.soomgil.ai.application;

/**
 * intent를 실행할 때 잘못 분류되면 사용자가 입는 피해의 크기.
 *
 * <p>안전 정책은 이 등급에 따라 실행 문턱을 다르게 적용한다. 조회는 잘못 분류되어도 데이터가
 * 바뀌지 않으므로 문턱을 두지 않고, 삭제처럼 되돌리기 부담이 큰 작업만 표현 근거를 요구한다.
 */
public enum AiIntentRisk {

	/** 도구를 쓰지 않는다. 대화·안내·되묻기. */
	NONE,

	/** 조회만 한다. 잘못 분류되어도 데이터가 바뀌지 않는다. */
	READ,

	/** 데이터를 바꾸지만 undo 또는 재실행으로 쉽게 회복된다. */
	REVERSIBLE,

	/** 기존 일정 항목을 제거한다. 분류가 틀리면 사용자가 만든 내용이 사라진다. */
	DESTRUCTIVE
}
