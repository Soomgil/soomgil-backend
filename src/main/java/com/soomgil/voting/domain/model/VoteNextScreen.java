package com.soomgil.voting.domain.model;

/**
 * 여행 방 진입 시 사용자에게 먼저 보여줄 화면.
 *
 * <p>프론트 라우터 가드는 이 값 하나만 보고 분기한다. 서버가 세션 상태와 참여 상태를 조합해
 * 계산하므로 클라이언트가 상태 조합을 다시 해석할 필요가 없다.
 */
public enum VoteNextScreen {

	/** 아직 제출하지 않은 참여자에게 지도보다 먼저 보여줄 투표 화면. */
	VOTE,

	/** 제출을 마쳤고 투표가 끝나기를 기다리는 대기 화면. */
	WAITING,

	/** 투표와 무관하게 지도 화면으로 이동. */
	MAP
}
